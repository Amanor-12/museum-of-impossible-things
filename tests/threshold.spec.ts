import { expect, test } from '@playwright/test'

test('a horizontal drag opens the rendered fault and carries the opening across the visit', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('./')
  await expect(page.getByRole('heading', { name: 'The Museum of Impossible Things.' })).toBeVisible()
  const canvas = page.locator('canvas[data-rendered]')
  await expect(canvas).toBeVisible()
  const closed = await canvas.screenshot()
  const stillPixels = await canvas.evaluate((node: HTMLCanvasElement) => node.width * node.height)
  const fault = page.getByRole('slider', { name: 'Opening in the wall' })
  await expect(fault).toHaveAttribute('aria-valuenow', '8')
  const bounds = await fault.boundingBox()
  if (!bounds) throw new Error('The opening has no pointer target')
  await page.mouse.move(bounds.x + bounds.width / 2, bounds.y + bounds.height / 2)
  await page.mouse.down()
  await page.mouse.move(bounds.x + bounds.width / 2 + 260, bounds.y + bounds.height / 2, { steps: 8 })
  await expect(canvas).toHaveAttribute('data-quality', 'interactive')
  expect(await canvas.evaluate((node: HTMLCanvasElement) => node.width * node.height)).toBeLessThan(stillPixels / 2)
  await page.mouse.up()
  await expect(canvas).toHaveAttribute('data-quality', 'still')
  const value = await fault.getAttribute('aria-valuenow')
  expect(Number(value)).toBeGreaterThan(57)
  await expect.poll(async () => (await canvas.screenshot()).equals(closed)).toBe(false)
  await page.getByRole('button', { name: 'Cross the threshold' }).click()
  await expect(page.getByRole('heading', { name: 'The displaced room' })).toBeFocused()
  await page.getByRole('button', { name: 'Blue light' }).click()
  await expect(page.getByRole('button', { name: 'Blue light' })).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('button', { name: 'Approach the inscription' }).click()
  const beforeInk = await canvas.screenshot()
  const input = page.getByLabel('Your inscription')
  await input.fill('<Room> remembers.')
  await input.press('Enter')
  await expect(page.getByRole('status')).toHaveText('<Room> remembers.')
  await expect.poll(async () => (await canvas.screenshot()).equals(beforeInk)).toBe(false)
  await page.getByRole('button', { name: 'Enter the inversion' }).click()
  await page.getByRole('button', { name: 'Invert gravity' }).click()
  await expect(page.getByRole('button', { name: 'Restore gravity' })).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('button', { name: 'Look back' }).click()
  await page.getByText('Read the inscription', { exact: true }).click()
  await expect(page.locator('.inscription-transcript p')).toHaveText('<Room> remembers.')
  await expect(page.locator('.field-record')).toContainText('Blue light')
  await expect(page.locator('.field-record')).toContainText('Inverted')
  const [print] = await Promise.all([
    page.waitForEvent('download'),
    page.getByRole('button', { name: 'Download your field record' }).click(),
  ])
  expect(print.suggestedFilename()).toBe('museum-field-record.png')
  expect(await print.failure()).toBeNull()
  await page.goBack()
  await expect(page.getByRole('button', { name: 'Restore gravity' })).toBeVisible()
  await page.goBack()
  await expect(page.getByLabel('Your inscription')).toHaveValue('<Room> remembers.')
  await page.getByRole('navigation', { name: 'Museum movements' }).getByRole('button', { name: 'The threshold' }).click()
  await expect(fault).toHaveAttribute('aria-valuenow', value!)
  expect(errors).toEqual([])
})

test('mobile layout keeps the fault reachable and provides a keyboard-operable fallback', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('./?flat')
  await expect(page.locator('canvas[data-rendered]')).toHaveCount(0)
  const fault = page.getByRole('slider', { name: 'Opening in the wall' })
  await expect(fault).toBeInViewport()
  const panel = page.locator('.threshold-fallback span').first()
  const before = await panel.evaluate(node => getComputedStyle(node).translate)
  await fault.press('ArrowRight')
  await expect(fault).toHaveAttribute('aria-valuenow', '18')
  await expect.poll(() => panel.evaluate(node => getComputedStyle(node).translate)).not.toBe(before)
  await fault.press('End')
  await expect(fault).toHaveAttribute('aria-valuetext', '100 percent open')
  await page.getByRole('button', { name: 'Cross the threshold' }).click()
  await expect(page.getByRole('heading', { name: 'The displaced room' })).toBeVisible()
  await page.getByRole('button', { name: 'Index' }).click()
  const index = page.getByRole('dialog')
  await expect(index).toBeVisible()
  await index.getByText('Field notes', { exact: true }).click()
  await expect(index.getByText('The suspended foil', { exact: true })).toBeVisible()
  await expect(index.getByRole('link', { name: /original exhibition archive/ })).toHaveAttribute('href', /\?archive$/)
  await page.keyboard.press('Escape')
  await expect(index).toBeHidden()
  await expect(page.getByRole('button', { name: 'Index' })).toBeFocused()
  await expect(page.getByRole('button', { name: 'Motion off' })).toHaveAttribute('aria-pressed', 'false')
  await page.getByRole('button', { name: 'Motion off' }).click()
  await expect(page.getByRole('button', { name: 'Motion on' })).toHaveAttribute('aria-pressed', 'true')
  await page.reload()
  await expect(page.getByRole('button', { name: 'Motion on' })).toBeVisible()
  const asset = await page.locator('.threshold-fallback').evaluate(node => getComputedStyle(node).backgroundImage.match(/url\("([^"]+)"\)/)?.[1])
  expect(asset).toBeTruthy()
  expect((await page.request.get(asset!)).ok()).toBeTruthy()
})
