import { expect, test } from '@playwright/test'

test('real-time arrival, threshold and sculpture controls', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
  await page.goto('./?archive')
  await expect(page.getByRole('heading', { name: 'Reality is a suggestion.' })).toBeVisible()
  await expect(page.locator('.gallery-art canvas')).toBeVisible()
  await page.getByRole('button', { name: 'Enter the impossible' }).click()
  await expect(page.getByRole('heading', { name: 'The Threshold' })).toBeFocused()
  await expect(page.locator('.gallery-art canvas')).toBeVisible()
  await page.getByRole('button', { name: 'Enter exhibition 01' }).click()
  await expect(page.getByRole('heading', { name: 'The Weight of Light' })).toBeVisible()
  const canvas = page.locator('.gallery-art canvas')
  await expect(canvas).toBeVisible()
  const restingArtwork = await canvas.screenshot()
  await page.getByRole('slider', { name: 'The seam' }).fill('51')
  await expect.poll(async () => (await canvas.screenshot()).equals(restingArtwork)).toBe(false)
  for (const mode of ['Fluid', 'Spectral', 'Solid']) {
    await page.getByRole('button', { name: mode, exact: true }).click()
    await expect(page.getByRole('button', { name: mode, exact: true })).toHaveAttribute('aria-pressed', 'true')
  }
  await page.getByRole('group', { name: /three polished metal ribbons/i }).press('ArrowRight')
  await page.getByRole('button', { name: 'Reset orientation' }).click()
  await expect(page.getByRole('button', { name: 'Motion off' })).toBeVisible()
  await page.getByRole('button', { name: 'Motion off' }).click()
  await expect(page.getByRole('button', { name: 'Motion on' })).toHaveAttribute('aria-pressed', 'true')
  await page.reload()
  await expect(page.getByRole('button', { name: 'Motion on' })).toBeVisible()
  expect(errors).toEqual([])
})

test('typography accepts text through the keyboard and resets', async ({ page }) => {
  await page.goto('./?archive#words')
  const input = page.getByLabel('Your phrase')
  await input.fill('<b>WORDS</b>')
  await input.press('Enter')
  const artwork = page.getByRole('button', { name: 'Interact with typographic artwork: <b>WORDS</b>' })
  await expect(artwork.locator('text')).toHaveText('<B>WORDS</B>')
  await expect(artwork.locator('b')).toHaveCount(0)
  await artwork.press('Enter')
  await page.getByRole('button', { name: 'Fragment' }).click()
  await expect(artwork.locator('g[clip-path]')).toHaveCount(12)
  await page.getByRole('button', { name: 'Liquid' }).click()
  await expect(artwork.locator('text')).toHaveAttribute('filter', 'url(#liquid)')
  await page.getByRole('button', { name: 'Reset typography' }).click()
  await expect(input).toBeEmpty()
  await expect(page.getByRole('button', { name: /artwork: language moves/i })).toBeVisible()
})

test('index, architecture and exit work in portrait and landscape', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('./?archive#room')
  await expect(page.locator('.gallery-art canvas')).toBeVisible()
  await expect(page.getByRole('slider', { name: 'The seam' })).toBeInViewport()
  const depth = page.getByRole('slider', { name: 'Passage depth' })
  await depth.press('End')
  await expect(depth).toHaveValue('1')
  await page.getByRole('button', { name: 'Fold the room' }).click()
  await expect(page.getByRole('button', { name: 'Unfold the room' })).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('button', { name: 'Exhibition index' }).click()
  const directory = page.getByRole('dialog')
  await expect(directory).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(directory).toBeHidden()
  await page.getByRole('button', { name: 'Next room' }).click()
  await expect(page.getByRole('heading', { name: 'The Impossible Was Never the Problem.' })).toBeVisible()
  await page.getByRole('button', { name: 'Return to entrance', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Reality is a suggestion.' })).toBeVisible()
  for (const size of [{ width: 390, height: 844 }, { width: 844, height: 390 }]) {
    await page.setViewportSize(size)
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(size.width)
  }
  await page.getByRole('button', { name: 'Exhibition index' }).click()
  await directory.getByRole('button', { name: /Words That Refuse/ }).click()
  await expect(page.getByRole('heading', { name: /Words That Refuse/ })).toBeVisible()
  await expect(directory).toBeHidden()
})

test('non-WebGL visitors receive the artwork and can browse', async ({ page }) => {
  await page.goto('./?archive&flat')
  await expect(page.locator('.gallery-art canvas')).toHaveCount(0)
  const fallback = page.getByRole('img', { name: /three polished metal ribbons/i })
  await expect(fallback).toBeVisible()
  const url = await fallback.evaluate(element => getComputedStyle(element).backgroundImage.slice(5, -2))
  expect((await page.request.get(url)).ok()).toBeTruthy()
  await page.getByRole('button', { name: 'The Room That Breathes' }).click()
  await expect(page.getByRole('img', { name: /hexagonal passageways/i })).toBeVisible()
})

test('the same seam passes through light, words, and architecture', async ({ page }) => {
  await page.goto('./?archive&flat#threshold')
  const seam = page.getByRole('slider', { name: 'The seam' })
  await expect(seam).toHaveAttribute('aria-valuetext', 'Dormant')
  await seam.fill('52')
  const strainTrace = await page.locator('.seam-trace').getAttribute('d')
  await page.getByRole('button', { name: 'Enter exhibition 01' }).click()
  await expect(seam).toHaveValue('52')
  await expect(page.locator('.fallback-light')).not.toHaveCSS('translate', '0px')
  await page.getByRole('button', { name: 'Next room' }).click()
  await expect(page.locator('.word-art [clip-path]')).toHaveCount(12)
  await page.getByRole('button', { name: 'Next room' }).click()
  await expect(page.locator('.seam-trace')).toHaveAttribute('d', strainTrace!)
  await seam.press('ArrowRight')
  await expect(seam).toHaveValue('53')
  await page.getByRole('button', { name: 'Clear seam' }).click()
  await expect(seam).toHaveValue('0')
  await expect(page.getByRole('button', { name: 'Clear seam' })).toBeDisabled()
})
